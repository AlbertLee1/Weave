type goGenerator struct{}

func (g *goGenerator) Language() string { return "go" }

// Generate emits the SDK in the per-ontology layout required by US-420:
//
//	go.mod                          (root)
//	pkg/<ontology>/client.go        (Client + middleware/retry/telemetry + ListOptions/ListResult)
//	pkg/<ontology>/objects.go       (object structs + per-type Get/List/Search + linkedObjects)
//	pkg/<ontology>/actions.go       (action param structs + Apply<Action> methods)
//	pkg/<ontology>/functions.go     (per-Function Execute<Name> wrappers + generic ExecuteFunction)
//	examples/telemetry_otel.go      (OpenTelemetry-style instrumenter, build-tagged ignore)
//	.weave-sdk.json + CHANGELOG.md  (via appendVersionFiles)
func (g *goGenerator) Generate(_ context.Context, schema OntologySchema) ([]GeneratedFile, error) {
	pkgName := goPackageName(schema.Ontology.APIName)
	modName := fmt.Sprintf("weave-sdk/%s", schema.Ontology.APIName)
	pkgDir := path.Join("pkg", pkgName)
	pkgImportPath := fmt.Sprintf("%s/%s", modName, pkgDir)

	var files []GeneratedFile

	client, err := g.generateClient(pkgName, schema)
	if err != nil {
		return nil, fmt.Errorf("generate client: %w", err)
	}
	files = append(files, GeneratedFile{Path: path.Join(pkgDir, "client.go"), Content: client})

	objects, err := g.generateObjects(pkgName, schema)
	if err != nil {
		return nil, fmt.Errorf("generate objects: %w", err)
	}
	files = append(files, GeneratedFile{Path: path.Join(pkgDir, "objects.go"), Content: objects})

	actions, err := g.generateActions(pkgName, schema)
	if err != nil {
		return nil, fmt.Errorf("generate actions: %w", err)
	}
	files = append(files, GeneratedFile{Path: path.Join(pkgDir, "actions.go"), Content: actions})

	functions, err := g.generateFunctions(pkgName, schema)
	if err != nil {
		return nil, fmt.Errorf("generate functions: %w", err)
	}
	files = append(files, GeneratedFile{Path: path.Join(pkgDir, "functions.go"), Content: functions})

	files = append(files, GeneratedFile{Path: "go.mod", Content: g.generateGoMod(modName)})

	example, err := g.generateTelemetryExample(pkgImportPath, pkgName)
	if err != nil {
		return nil, fmt.Errorf("generate telemetry example: %w", err)
	}
	files = append(files, GeneratedFile{Path: "examples/telemetry_otel.go", Content: example})

	files = appendVersionFiles(files, schema, g.Language())
	return files, nil
}

func (g *goGenerator) generateObjects(pkgName string, schema OntologySchema) ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by Weave SDK Generator — DO NOT EDIT.\n\n")
	fmt.Fprintf(&buf, "package %s\n\n", pkgName)

	needsTime, needsJSON := false, false
	for _, ot := range schema.ObjectTypes {
		for _, p := range ot.Properties {
			switch types.BaseType(p.BaseType) {
			case types.Timestamp:
				needsTime = true
			case types.Geoshape:
				needsJSON = true
			}
		}
	}

	imports := []string{
		"\"context\"",
		"\"fmt\"",
		"\"net/url\"",
	}
	if needsJSON {
		imports = append(imports, "\"encoding/json\"")
	}
	if needsTime {
		imports = append(imports, "\"time\"")
	}
	buf.WriteString("import (\n")
	for _, imp := range imports {
		fmt.Fprintf(&buf, "\t%s\n", imp)
	}
	buf.WriteString(")\n\n")

	for _, ot := range schema.ObjectTypes {
		displayName := ot.DisplayName
		if displayName == "" {
			displayName = ot.APIName
		}
		fmt.Fprintf(&buf, "// %s represents a %s object.\n", ot.APIName, displayName)
		fmt.Fprintf(&buf, "type %s struct {\n", ot.APIName)
		for _, p := range ot.Properties {
			goType := resolveGoType(p.BaseType, p.IsArray)
			fmt.Fprintf(&buf, "\t%s %s `json:\"%s\"`\n", exportedFieldName(p.APIName), goType, p.APIName)
		}
		buf.WriteString("}\n\n")
	}

	bySource := goLinksBySource(schema)

	for _, ot := range schema.ObjectTypes {
		fmt.Fprintf(&buf, "// Get%s fetches an %s by primary key.\n", ot.APIName, ot.APIName)
		fmt.Fprintf(&buf, "func (c *Client) Get%s(ctx context.Context, pk string) (*%s, error) {\n", ot.APIName, ot.APIName)
		fmt.Fprintf(&buf, "\tvar out %s\n", ot.APIName)
		fmt.Fprintf(&buf, "\tpath := fmt.Sprintf(\"/api/v2/ontologies/%%s/objects/%s/%%s\", url.PathEscape(c.Ontology), url.PathEscape(pk))\n", ot.APIName)
		buf.WriteString("\tif err := c.do(ctx, \"GET\", path, nil, &out); err != nil {\n")
		buf.WriteString("\t\treturn nil, err\n")
		buf.WriteString("\t}\n")
		buf.WriteString("\treturn &out, nil\n")
		buf.WriteString("}\n\n")

		fmt.Fprintf(&buf, "// List%s paginates over %s objects.\n", ot.APIName, ot.APIName)
		fmt.Fprintf(&buf, "func (c *Client) List%s(ctx context.Context, opts *ListOptions) (*ListResult[%s], error) {\n", ot.APIName, ot.APIName)
		fmt.Fprintf(&buf, "\tpath := appendListQuery(fmt.Sprintf(\"/api/v2/ontologies/%%s/objects/%s\", url.PathEscape(c.Ontology)), opts)\n", ot.APIName)
		fmt.Fprintf(&buf, "\tvar out ListResult[%s]\n", ot.APIName)
		buf.WriteString("\tif err := c.do(ctx, \"GET\", path, nil, &out); err != nil {\n")
		buf.WriteString("\t\treturn nil, err\n")
		buf.WriteString("\t}\n")
		buf.WriteString("\treturn &out, nil\n")
		buf.WriteString("}\n\n")

		fmt.Fprintf(&buf, "// Search%s searches %s objects using the given where clause.\n", ot.APIName, ot.APIName)
		fmt.Fprintf(&buf, "func (c *Client) Search%s(ctx context.Context, where map[string]interface{}, opts *ListOptions) (*ListResult[%s], error) {\n", ot.APIName, ot.APIName)
		fmt.Fprintf(&buf, "\tpath := fmt.Sprintf(\"/api/v2/ontologies/%%s/objects/%s/search\", url.PathEscape(c.Ontology))\n", ot.APIName)
		buf.WriteString("\tbody := map[string]interface{}{\"where\": where}\n")
		buf.WriteString("\tif opts != nil {\n")
		buf.WriteString("\t\tif opts.PageSize > 0 {\n")
		buf.WriteString("\t\t\tbody[\"pageSize\"] = opts.PageSize\n")
		buf.WriteString("\t\t}\n")
		buf.WriteString("\t\tif opts.PageToken != \"\" {\n")
		buf.WriteString("\t\t\tbody[\"pageToken\"] = opts.PageToken\n")
		buf.WriteString("\t\t}\n")
		buf.WriteString("\t}\n")
		fmt.Fprintf(&buf, "\tvar out ListResult[%s]\n", ot.APIName)
		buf.WriteString("\tif err := c.do(ctx, \"POST\", path, body, &out); err != nil {\n")
		buf.WriteString("\t\treturn nil, err\n")
		buf.WriteString("\t}\n")
		buf.WriteString("\treturn &out, nil\n")
		buf.WriteString("}\n\n")

		for _, lt := range bySource[ot.APIName] {
			fmt.Fprintf(&buf, "// LinkedObjects%s%s traverses the %s link from a source %s primary key.\n",
				ot.APIName, pascalCase(lt.APIName), lt.APIName, ot.APIName)
			fmt.Fprintf(&buf, "func (c *Client) LinkedObjects%s%s(ctx context.Context, pk string) ([]%s, error) {\n",
				ot.APIName, pascalCase(lt.APIName), lt.TargetObjectType)
			fmt.Fprintf(&buf, "\tpath := fmt.Sprintf(\"/api/v2/ontologies/%%s/objects/%s/%%s/links/%s\", url.PathEscape(c.Ontology), url.PathEscape(pk))\n",
				lt.SourceObjectType, lt.APIName)
			fmt.Fprintf(&buf, "\tvar wrap struct{ Data []%s `json:\"data\"` }\n", lt.TargetObjectType)
			buf.WriteString("\tif err := c.do(ctx, \"GET\", path, nil, &wrap); err != nil {\n")
			buf.WriteString("\t\treturn nil, err\n")
			buf.WriteString("\t}\n")
			buf.WriteString("\treturn wrap.Data, nil\n")
			buf.WriteString("}\n\n")
		}
	}

	if needsJSON {
		buf.WriteString("var _ json.RawMessage\n")
	}
	if needsTime {
		buf.WriteString("var _ time.Time\n")
	}

	return format.Source(buf.Bytes())
}

func (g *goGenerator) generateActions(pkgName string, schema OntologySchema) ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by Weave SDK Generator — DO NOT EDIT.\n\n")
	fmt.Fprintf(&buf, "package %s\n\n", pkgName)
	buf.WriteString("import (\n")
	buf.WriteString("\t\"context\"\n")
	buf.WriteString("\t\"fmt\"\n")
	buf.WriteString("\t\"net/url\"\n")
	buf.WriteString(")\n\n")

	for _, at := range schema.ActionTypes {
		if len(at.Parameters) == 0 {
			continue
		}
		fmt.Fprintf(&buf, "// %sParams holds parameters for the %s action.\n", pascalCase(at.APIName), at.APIName)
		fmt.Fprintf(&buf, "type %sParams struct {\n", pascalCase(at.APIName))
		for _, p := range at.Parameters {
			goType := resolveGoType(p.BaseType, false)
			if !p.Required {
				goType = "*" + goType
			}
			fmt.Fprintf(&buf, "\t%s %s `json:\"%s\"`\n", exportedFieldName(p.ID), goType, p.ID)
		}
		buf.WriteString("}\n\n")
	}

	for _, at := range schema.ActionTypes {
		method := "Apply" + pascalCase(at.APIName)
		if len(at.Parameters) > 0 {
			fmt.Fprintf(&buf, "// %s applies the %s action.\n", method, at.APIName)
			fmt.Fprintf(&buf, "func (c *Client) %s(ctx context.Context, params %sParams) error {\n", method, pascalCase(at.APIName))
			fmt.Fprintf(&buf, "\tpath := fmt.Sprintf(\"/api/v2/ontologies/%%s/actions/%s/apply\", url.PathEscape(c.Ontology))\n", at.APIName)
			buf.WriteString("\treturn c.do(ctx, \"POST\", path, map[string]interface{}{\"parameters\": params}, nil)\n")
		} else {
			fmt.Fprintf(&buf, "// %s applies the %s action.\n", method, at.APIName)
			fmt.Fprintf(&buf, "func (c *Client) %s(ctx context.Context) error {\n", method)
			fmt.Fprintf(&buf, "\tpath := fmt.Sprintf(\"/api/v2/ontologies/%%s/actions/%s/apply\", url.PathEscape(c.Ontology))\n", at.APIName)
			buf.WriteString("\treturn c.do(ctx, \"POST\", path, nil, nil)\n")
		}
		buf.WriteString("}\n\n")
	}

	if len(schema.ActionTypes) == 0 {
		// Keep imports referenced even when no actions are emitted so the file
		// still passes go vet. The compiler treats blank-identifier underscore
		// references as "use" without producing runtime overhead.
		buf.WriteString("var (\n")
		buf.WriteString("\t_ = context.Background\n")
		buf.WriteString("\t_ = fmt.Sprintf\n")
		buf.WriteString("\t_ = url.PathEscape\n")
		buf.WriteString(")\n")
	}

	return format.Source(buf.Bytes())
}

func (g *goGenerator) generateFunctions(pkgName string, schema OntologySchema) ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by Weave SDK Generator — DO NOT EDIT.\n\n")
	fmt.Fprintf(&buf, "package %s\n\n", pkgName)
	buf.WriteString("import (\n")
	buf.WriteString("\t\"context\"\n")
	buf.WriteString("\t\"fmt\"\n")
	buf.WriteString("\t\"net/url\"\n")
	buf.WriteString(")\n\n")

	buf.WriteString(`// FunctionExecuteRequest is the wire body the server expects on
// POST /api/v2/ontologies/{ontology}/functions/{ref}/execute.
type FunctionExecuteRequest struct {
	Parameters map[string]interface{} ` + "`json:\"parameters,omitempty\"`" + `
}

// FunctionExecuteResponse is the wire envelope returned by the server.
// Result is left as a raw map so callers can either unmarshal it themselves or
// pass an out pointer to ExecuteFunction for typed decoding.
type FunctionExecuteResponse struct {
	Result map[string]interface{} ` + "`json:\"result\"`" + `
}

// ExecuteFunction is the generic wrapper for executing any Function by
// reference (rid, name, or name@version). It threads parameters through the
// canonical wire envelope and decodes the response into out, which may be nil
// to discard the result.
func (c *Client) ExecuteFunction(ctx context.Context, ref string, params map[string]interface{}, out interface{}) error {
	path := fmt.Sprintf("/api/v2/ontologies/%s/functions/%s/execute",
		url.PathEscape(c.Ontology), url.PathEscape(ref))
	body := FunctionExecuteRequest{Parameters: params}
	if out == nil {
		return c.do(ctx, "POST", path, body, nil)
	}
	return c.do(ctx, "POST", path, body, out)
}

`)

	for _, fn := range schema.Functions {
		ref := fn.Name
		if fn.Version != "" {
			ref = fn.Name + "@" + fn.Version
		}
		method := "Execute" + pascalCase(goSafeIdent(fn.Name))
		fmt.Fprintf(&buf, "// %s executes the %s Function (ref=%q).\n", method, fn.Name, ref)
		fmt.Fprintf(&buf, "func (c *Client) %s(ctx context.Context, params map[string]interface{}, out interface{}) error {\n", method)
		fmt.Fprintf(&buf, "\treturn c.ExecuteFunction(ctx, %q, params, out)\n", ref)
		buf.WriteString("}\n\n")
	}

	return format.Source(buf.Bytes())
}

