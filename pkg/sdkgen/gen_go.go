// exportedFieldName converts a camelCase API name to an exported Go field name.
// Trailing "Id" is rewritten to "ID" per Go's initialism convention.
func exportedFieldName(name string) string {
	if name == "" {
		return name
	}
	upper := strings.ToUpper(name[:1]) + name[1:]
	if strings.HasSuffix(upper, "Id") {
		upper = upper[:len(upper)-2] + "ID"
	}
	return upper
}

// goPackageName sanitises an ontology API name into a valid Go package
// identifier — lowercase letters / digits / underscores, leading digit
// prefixed with `_`. Empty input falls back to `weavesdk` so a degenerate
// schema still emits a parseable package declaration.
func goPackageName(s string) string {
	var b strings.Builder
	for _, r := range s {
		switch {
		case r >= 'A' && r <= 'Z':
			b.WriteRune(r + ('a' - 'A'))
		case (r >= 'a' && r <= 'z') || (r >= '0' && r <= '9') || r == '_':
			b.WriteRune(r)
		}
	}
	out := b.String()
	if out == "" {
		return "weavesdk"
	}
	if out[0] >= '0' && out[0] <= '9' {
		out = "_" + out
	}
	return out
}

// goSafeIdent sanitises an arbitrary identifier (e.g. a Function name that
// may contain dots, hyphens, etc.) into a string that can flow into
// pascalCase to produce a valid Go method receiver name. Non-alphanumeric
// runes collapse into nothing; runs of letters/digits round-trip unchanged.
func goSafeIdent(s string) string {
	var b strings.Builder
	upperNext := false
	for i, r := range s {
		switch {
		case (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || (r >= '0' && r <= '9'):
			if upperNext {
				if r >= 'a' && r <= 'z' {
					r = r - ('a' - 'A')
				}
				upperNext = false
			}
			if i == 0 && r >= '0' && r <= '9' {
				b.WriteRune('_')
			}
			b.WriteRune(r)
		default:
			upperNext = true
		}
	}
	out := b.String()
	if out == "" {
		return "Function"
	}
	return out
}
