package sdkgen

import (
	"bytes"
	"context"
	"fmt"

	"github.com/liyang/weave/pkg/types"
)

type pythonGenerator struct{}

func (g *pythonGenerator) Language() string { return "python" }

func (g *pythonGenerator) Generate(_ context.Context, schema OntologySchema) ([]GeneratedFile, error) {
	var files []GeneratedFile

	// models.py — Pydantic BaseModel per ObjectType
	models, err := g.generateModels(schema)
	if err != nil {
		return nil, fmt.Errorf("generate models: %w", err)
	}
	files = append(files, GeneratedFile{Path: "weave_sdk/models.py", Content: models})

	// client.py
	client, err := g.generateClient(schema)
	if err != nil {
		return nil, fmt.Errorf("generate client: %w", err)
	}
	files = append(files, GeneratedFile{Path: "weave_sdk/client.py", Content: client})

	// __init__.py
	init := g.generateInit(schema)
	files = append(files, GeneratedFile{Path: "weave_sdk/__init__.py", Content: init})

	// pyproject.toml
	proj := g.generatePyproject(schema)
	files = append(files, GeneratedFile{Path: "pyproject.toml", Content: proj})

	// py.typed — PEP 561 marker so downstream mypy picks up inline type hints
	files = append(files, GeneratedFile{Path: "weave_sdk/py.typed", Content: []byte("# PEP 561 marker\n")})

	return files, nil
}

func (g *pythonGenerator) generateModels(schema OntologySchema) ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString("# Auto-generated by Weave SDK Generator — do not edit.\n\n")
	buf.WriteString("from __future__ import annotations\n\n")
	buf.WriteString("import datetime\nfrom decimal import Decimal\nfrom typing import Any, Optional\n\n")
	buf.WriteString("from pydantic import BaseModel\n\n")

	for _, ot := range schema.ObjectTypes {
		fmt.Fprintf(&buf, "\nclass %s(BaseModel):\n", ot.APIName)
		if len(ot.Properties) == 0 {
			buf.WriteString("    pass\n")
			continue
		}
		for _, p := range ot.Properties {
			pyType := resolvePythonType(p.BaseType, p.IsArray)
			fmt.Fprintf(&buf, "    %s: %s\n", p.APIName, pyType)
		}
	}
	buf.WriteString("\n")

	// Action parameter models
	for _, at := range schema.ActionTypes {
		if len(at.Parameters) == 0 {
			continue
		}
		fmt.Fprintf(&buf, "\nclass %sParams(BaseModel):\n", pascalCase(at.APIName))
		for _, p := range at.Parameters {
			pyType := resolvePythonType(p.BaseType, false)
			if !p.Required {
				pyType = fmt.Sprintf("Optional[%s]", pyType)
			}
			fmt.Fprintf(&buf, "    %s: %s\n", p.ID, pyType)
		}
	}

	return buf.Bytes(), nil
}

