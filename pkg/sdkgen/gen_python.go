func (g *pythonGenerator) generateInit(schema OntologySchema) []byte {
	var buf bytes.Buffer
	buf.WriteString("# Auto-generated by Weave SDK Generator — do not edit.\n\n")
	buf.WriteString("from .client import WeaveClient\n")
	buf.WriteString("from .models import (\n")
	for _, ot := range schema.ObjectTypes {
		fmt.Fprintf(&buf, "    %s,\n", ot.APIName)
	}
	for _, at := range schema.ActionTypes {
		if len(at.Parameters) > 0 {
			fmt.Fprintf(&buf, "    %sParams,\n", pascalCase(at.APIName))
		}
	}
	buf.WriteString(")\n\n")
	buf.WriteString("__all__ = [\n")
	buf.WriteString("    \"WeaveClient\",\n")
	for _, ot := range schema.ObjectTypes {
		fmt.Fprintf(&buf, "    \"%s\",\n", ot.APIName)
	}
	for _, at := range schema.ActionTypes {
		if len(at.Parameters) > 0 {
			fmt.Fprintf(&buf, "    \"%sParams\",\n", pascalCase(at.APIName))
		}
	}
	buf.WriteString("]\n")
	return buf.Bytes()
}

func (g *pythonGenerator) generatePyproject(schema OntologySchema) []byte {
	name := schema.Ontology.APIName
	return []byte(fmt.Sprintf(`[project]
name = "weave-%s-sdk"
version = "0.1.0"
requires-python = ">=3.10"
dependencies = [
    "httpx>=0.25.0",
    "pydantic>=2.0.0",
]
`, name))
}

func resolvePythonType(baseType string, isArray bool) string {
	mapped, ok := pythonTypeMap[types.BaseType(baseType)]
	if !ok {
		mapped = "Any"
	}
	if isArray {
		return fmt.Sprintf("list[%s]", mapped)
	}
	return mapped
}

// snakeCase converts camelCase to snake_case.
func snakeCase(s string) string {
	var result bytes.Buffer
	for i, r := range s {
		if i > 0 && r >= 'A' && r <= 'Z' {
			result.WriteByte('_')
		}
		if r >= 'A' && r <= 'Z' {
			result.WriteRune(r + ('a' - 'A'))
		} else {
			result.WriteRune(r)
		}
	}
	return result.String()
}
