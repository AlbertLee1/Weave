type javaGenerator struct{}

func (g *javaGenerator) Language() string { return "java" }

// Generate emits the Java SDK in a Maven project layout:
//
//	pom.xml                                                 (root)
//	src/main/java/com/weave/<ontology>/WeaveClient.java     (single file SDK)
//	.weave-sdk.json + CHANGELOG.md                          (via appendVersionFiles)
//
// The single-file layout keeps every public type — Client, Middleware,
// RetryPolicy, TelemetryHooks, JSON helper, ListOptions/ListResult, and the
// schema-driven POJOs — in one compilation unit so the SDK package directory
// stays tidy regardless of ontology size. The SDK depends only on the Java 11+
// standard library (java.net.http.HttpClient + java.util) so `mvn compile`
// succeeds with no third-party artifacts to resolve.
func (g *javaGenerator) Generate(_ context.Context, schema OntologySchema) ([]GeneratedFile, error) {
	pkg := javaPackageSegment(schema.Ontology.APIName)
	artifact := javaArtifactID(schema.Ontology.APIName)
	pkgDir := path.Join("src/main/java/com/weave", pkg)

	var files []GeneratedFile
	files = append(files, GeneratedFile{Path: "pom.xml", Content: g.generatePom(artifact)})
	files = append(files, GeneratedFile{Path: path.Join(pkgDir, "WeaveClient.java"), Content: g.generateClient(pkg, schema)})
	files = appendVersionFiles(files, schema, g.Language())
	return files, nil
}

func (g *javaGenerator) generatePom(artifactID string) []byte {
	return []byte(fmt.Sprintf(`<?xml version="1.0" encoding="UTF-8"?>
<project xmlns="http://maven.apache.org/POM/4.0.0">
    <modelVersion>4.0.0</modelVersion>
    <groupId>com.weave.sdk</groupId>
    <artifactId>%s</artifactId>
    <version>0.1.0</version>
    <packaging>jar</packaging>

    <properties>
        <maven.compiler.source>11</maven.compiler.source>
        <maven.compiler.target>11</maven.compiler.target>
        <project.build.sourceEncoding>UTF-8</project.build.sourceEncoding>
    </properties>
</project>
`, artifactID))
}

