// javaPackageSegment sanitises an ontology API name into a single Java
// package segment — lowercase letters / digits / underscores, leading digit
// prefixed with `_`. Empty input falls back to `weavesdk` so a degenerate
// schema still emits a valid package declaration.
func javaPackageSegment(s string) string {
	var b strings.Builder
	for _, r := range s {
		switch {
		case r >= 'A' && r <= 'Z':
			b.WriteRune(r + ('a' - 'A'))
		case (r >= 'a' && r <= 'z') || (r >= '0' && r <= '9') || r == '_':
			b.WriteRune(r)
		}
	}
	out := b.String()
	if out == "" {
		return "weavesdk"
	}
	if out[0] >= '0' && out[0] <= '9' {
		out = "_" + out
	}
	if isJavaReservedWord(out) {
		out = out + "_"
	}
	return out
}

// javaArtifactID derives a Maven-friendly artifactId — lowercase, digits,
// hyphens. Empty input → `weave-sdk`.
func javaArtifactID(s string) string {
	var b strings.Builder
	for _, r := range s {
		switch {
		case r >= 'A' && r <= 'Z':
			b.WriteRune(r + ('a' - 'A'))
		case (r >= 'a' && r <= 'z') || (r >= '0' && r <= '9'):
			b.WriteRune(r)
		default:
			b.WriteRune('-')
		}
	}
	out := strings.Trim(b.String(), "-")
	if out == "" {
		return "weave-sdk"
	}
	return "weave-" + out + "-sdk"
}

// javaSafeFieldName returns the API name unchanged unless it collides with a
// Java reserved word, in which case a trailing underscore is appended.
func javaSafeFieldName(name string) string {
	if isJavaReservedWord(name) {
		return name + "_"
	}
	return name
}

// javaSafeIdent sanitises an arbitrary identifier (Function names may contain
// dots, hyphens, slashes) so it can flow into pascalCase to produce a valid
// Java method name. Non-alphanumeric runes collapse the case-bump cursor;
// runs of letters/digits round-trip unchanged.
func javaSafeIdent(s string) string {
	var b strings.Builder
	upperNext := false
	for i, r := range s {
		switch {
		case (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || (r >= '0' && r <= '9'):
			if upperNext {
				if r >= 'a' && r <= 'z' {
					r = r - ('a' - 'A')
				}
				upperNext = false
			}
			if i == 0 && r >= '0' && r <= '9' {
				b.WriteRune('_')
			}
			b.WriteRune(r)
		default:
			upperNext = true
		}
	}
	out := b.String()
	if out == "" {
		return "Function"
	}
	return out
}

func isJavaReservedWord(s string) bool {
	_, ok := javaReservedWords[s]
	return ok
}

