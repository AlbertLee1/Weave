// resolveTSType maps a BaseType string to its TypeScript representation.
func resolveTSType(baseType string, isArray bool) string {
	mapped, ok := tsTypeMap[types.BaseType(baseType)]
	if !ok {
		mapped = "unknown"
	}
	if isArray {
		return mapped + "[]"
	}
	return mapped
}

// pascalCase converts a camelCase string to PascalCase.
func pascalCase(s string) string {
	if s == "" {
		return s
	}
	return strings.ToUpper(s[:1]) + s[1:]
}
