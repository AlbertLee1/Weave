func (g *tsGenerator) generateIndex(schema OntologySchema) []byte {
	var buf bytes.Buffer
	buf.WriteString("// Auto-generated by Weave SDK Generator — do not edit.\n\n")
	buf.WriteString("export * from './models';\n")
	buf.WriteString("export { WeaveClient } from './client';\n")
	return buf.Bytes()
}

func (g *tsGenerator) generatePackageJSON(schema OntologySchema) []byte {
	name := schema.Ontology.APIName
	return []byte(fmt.Sprintf(`{
  "name": "@weave/%s-sdk",
  "version": "0.1.0",
  "main": "dist/index.js",
  "types": "dist/index.d.ts",
  "scripts": {
    "build": "tsc"
  },
  "devDependencies": {
    "typescript": "^5.0.0"
  }
}
`, name))
}

