func (g *tsGenerator) generateIndex(_ OntologySchema) []byte {
	var buf bytes.Buffer
	buf.WriteString("// Auto-generated by Weave SDK Generator — do not edit.\n\n")
	buf.WriteString("export * from './models';\n")
	buf.WriteString("export * from './client';\n")
	return buf.Bytes()
}

