type tsGenerator struct{}

func (g *tsGenerator) Language() string { return "ts" }

func (g *tsGenerator) Generate(_ context.Context, schema OntologySchema) ([]GeneratedFile, error) {
	var files []GeneratedFile

	models, err := g.generateModels(schema)
	if err != nil {
		return nil, fmt.Errorf("generate models: %w", err)
	}
	files = append(files, GeneratedFile{Path: "src/models.ts", Content: models})

	client, err := g.generateClient(schema)
	if err != nil {
		return nil, fmt.Errorf("generate client: %w", err)
	}
	files = append(files, GeneratedFile{Path: "src/client.ts", Content: client})

	files = append(files, GeneratedFile{Path: "src/index.ts", Content: g.generateIndex(schema)})
	files = append(files, GeneratedFile{Path: "package.json", Content: g.generatePackageJSON(schema)})
	files = append(files, GeneratedFile{Path: "tsconfig.json", Content: g.generateTSConfig()})

	files = appendVersionFiles(files, schema, g.Language())
	return files, nil
}

func (g *tsGenerator) generateModels(schema OntologySchema) ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString("// Auto-generated by Weave SDK Generator — do not edit.\n\n")

	for _, ot := range schema.ObjectTypes {
		fmt.Fprintf(&buf, "export interface %s {\n", ot.APIName)
		for _, p := range ot.Properties {
			fmt.Fprintf(&buf, "  %s: %s;\n", p.APIName, resolveTSType(p.BaseType, p.IsArray))
		}
		buf.WriteString("}\n\n")
	}

	for _, at := range schema.ActionTypes {
		if len(at.Parameters) == 0 {
			continue
		}
		fmt.Fprintf(&buf, "export interface %sParams {\n", pascalCase(at.APIName))
		for _, p := range at.Parameters {
			tsType := resolveTSType(p.BaseType, false)
			optional := ""
			if !p.Required {
				optional = "?"
			}
			fmt.Fprintf(&buf, "  %s%s: %s;\n", p.ID, optional, tsType)
		}
		buf.WriteString("}\n\n")
	}

	return buf.Bytes(), nil
}

// linksBySource groups link types by their source ObjectType apiName.
func linksBySource(schema OntologySchema) map[string][]LinkTypeSchema {
	out := make(map[string][]LinkTypeSchema)
	for _, lt := range schema.LinkTypes {
		out[lt.SourceObjectType] = append(out[lt.SourceObjectType], lt)
	}
	return out
}

type tsClientView struct {
	Schema      OntologySchema
	ObjectTypes []tsObjectView
	ActionTypes []ActionTypeSchema
	ImportNames []string
}

type tsObjectView struct {
	APIName string
	Links   []LinkTypeSchema
}

func (g *tsGenerator) generateClient(schema OntologySchema) ([]byte, error) {
	bySource := linksBySource(schema)

	view := tsClientView{Schema: schema, ActionTypes: schema.ActionTypes}
	importSet := make(map[string]struct{})

	for _, ot := range schema.ObjectTypes {
		view.ObjectTypes = append(view.ObjectTypes, tsObjectView{
			APIName: ot.APIName,
			Links:   bySource[ot.APIName],
		})
		importSet[ot.APIName] = struct{}{}
		for _, lt := range bySource[ot.APIName] {
			importSet[lt.TargetObjectType] = struct{}{}
		}
	}
	for _, at := range schema.ActionTypes {
		if len(at.Parameters) > 0 {
			importSet[pascalCase(at.APIName)+"Params"] = struct{}{}
		}
	}

	for name := range importSet {
		view.ImportNames = append(view.ImportNames, name)
	}
	// Stable order for deterministic output.
	for i := 0; i < len(view.ImportNames); i++ {
		for j := i + 1; j < len(view.ImportNames); j++ {
			if view.ImportNames[j] < view.ImportNames[i] {
				view.ImportNames[i], view.ImportNames[j] = view.ImportNames[j], view.ImportNames[i]
			}
		}
	}

	tmpl := template.Must(template.New("client").Funcs(template.FuncMap{
		"pascalCase": pascalCase,
		"join":       strings.Join,
	}).Parse(tsClientTmplStr))

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, view); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

